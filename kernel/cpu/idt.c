static void idt_set_gate(uint8_t n, uint32_t handler, uint8_t flags) {
    idt[n].offset_low = handler & 0xFFFF;
    idt[n].selector = KERNEL_CODE_SELECTOR;
    idt[n].zero = 0;
    idt[n].type_attr = flags;
    idt[n].offset_high = (handler >> 16) & 0xFFFF;
}

void idt_init(void) {
    void (*handlers[48])(void) = {
        isr0, isr1, isr2, isr3, isr4, isr5, isr6, isr7,
        isr8, isr9, isr10, isr11, isr12, isr13, isr14, isr15,
        isr16, isr17, isr18, isr19, isr20, isr21, isr22, isr23,
        isr24, isr25, isr26, isr27, isr28, isr29, isr30, isr31,
        isr32, isr33, isr34, isr35, isr36, isr37, isr38, isr39,
        isr40, isr41, isr42, isr43, isr44, isr45, isr46, isr47
    };

    for (int i = 0; i < IDT_ENTRIES; i++) {
        idt_set_gate(i, 0, 0);
    }

    for (int i = 0; i < 48; i++) {
        idt_set_gate(i, (uint32_t)handlers[i], IDT_INTERRUPT_GATE);
    }

    idt_set_gate(128, (uint32_t)isr128, IDT_USER_INTERRUPT_GATE);

    idt_ptr.limit = sizeof(idt) - 1;
    idt_ptr.base = (uint32_t)&idt;

    __asm__ volatile ("lidt %0" : : "m"(idt_ptr));
}
